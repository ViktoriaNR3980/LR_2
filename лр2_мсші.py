import matplotlib.pyplot as plt
import numpy as np
from sklearn.model_selection import train_test_split

# Set styles for smooth plots
plt.rcParams['font.sans-serif'] = 'DejaVu Sans'
plt.rcParams['axes.edgecolor'] = '#cccccc'

# 1. ГЕНЕРАЦІЯ ТА НОРМАЛІЗАЦІЯ ДАНИХ
np.random.seed(42)

# 1000 випадкових значень у діапазоні [0; 10]
x_raw = np.sort(np.random.uniform(0, 10, 1000))

# функція f(x) = sin(x) - 3*cos(2x) + 2*sin(5x - 3.14) з шумом
y_true = np.sin(x_raw) - 3 * np.cos(2 * x_raw) + 2 * np.sin(5 * x_raw - np.pi)
noise = np.random.normal(0, 0.4, size=1000)
y = y_true + noise

# Нормалізація значений X в діапазон [0, 1]
x_min, x_max = x_raw.min(), x_raw.max()
x_norm = (x_raw - x_min) / (x_max - x_min)

# ГРАФІК 1: Згенеровані нормалізовані дані
plt.figure(figsize=(8, 5))
plt.scatter(x_norm, y, color='blue', alpha=0.5, s=15)
plt.title('Згенеровані дані', fontsize=13)
plt.xlabel('Ознака X (нормалізована)', fontsize=10)
plt.ylabel('Цільова змінна Y', fontsize=10)
plt.grid(True, linestyle='--', alpha=0.5)
plt.tight_layout()
plt.show()


# 2. РОЗПОДІЛ НА НАВЧАЛЬНУ ТА ТЕСТОВУ ВИБІРКИ (4 : 1)
X_train, X_test, y_train, y_test = train_test_split(
    x_norm, y, test_size=0.2, random_state=42
)

# ГРАФІК 2: Дані, розподілені у відношенні 4 : 1
plt.figure(figsize=(8, 5))
plt.scatter(
    X_train,
    y_train,
    color='blue',
    alpha=0.4,
    s=15,
    label='Навчальна вибірка (80%)',
)
plt.scatter(
    X_test,
    y_test,
    color='green',
    alpha=0.8,
    s=15,
    label='Тестова вибірка (20%)',
)
plt.title('Дані, розподілені у відношенні 4 (навчальна) : 1 (тестова)', fontsize=12)
plt.xlabel('Ознака X', fontsize=10)
plt.ylabel('Цільова змінна Y', fontsize=10)
plt.legend()
plt.grid(True, linestyle='--', alpha=0.5)
plt.tight_layout()
plt.show()

# 3. ФУНКЦІЇ KNN ТА КОЕФІЦІЄНТА ДЕТЕРМІНАЦІЇ R^2
def knnArray(X_tr, y_tr, X_te, k):
  """Реалізація KNN-регресора."""
  predictions = []
  for x_val in X_te:
    distances = np.abs(X_tr - x_val)
    k_indices = np.argsort(distances)[:k]
    predictions.append(np.mean(y_tr[k_indices]))
  return np.array(predictions)


def calculate_r2(y_true, y_pred):
  """Обчислення R^2 за формулами з конспекту: R2 = 1 - (SS_res / SS_tot)."""
  ss_res = np.sum((y_true - y_pred) ** 2)
  ss_tot = np.sum((y_true - np.mean(y_true)) ** 2)
  return 1 - (ss_res / ss_tot)

# 4. ОБРАХУНОК У ЦИКЛІ ДЛЯ ВІДШУКАННЯ ОПТИМАЛЬНОГО K
k_range = range(2, 350)
r2_scores = []

for k in k_range:
  y_pred_test = knnArray(X_train, y_train, X_test, k)
  r2_val = calculate_r2(y_test, y_pred_test)
  r2_scores.append(r2_val)

# Автоматичне знаходження індексу та значення для максимального R^2
best_idx = np.argmax(r2_scores)
best_k = k_range[best_idx]
best_r2 = r2_scores[best_idx]

print(f'Результат обчислення в циклі:')
print(f'Максимальне значення R2 = {best_r2:.6f} досягається при k = {best_k}')

# 5. ГРАФІКИ РЕЗУЛЬТАТІВ ТА ЗАЛЕЖНОСТЕЙ
# ГРАФІК 3: Результат роботи KNN-регресора для оптимального K
x_grid = np.linspace(0, 1, 500)
y_best_grid = knnArray(X_train, y_train, x_grid, best_k)

plt.figure(figsize=(8, 5))
plt.scatter(x_norm, y, color='black', alpha=0.3, s=20)
plt.plot(x_grid, y_best_grid, color='red', linewidth=2)
plt.title(f'K = {best_k}, R2 = {best_r2:.6f}', fontsize=12)
plt.xlabel('Ознака X', fontsize=10)
plt.ylabel('Цільова змінна Y', fontsize=10)
plt.grid(True, linestyle='--', alpha=0.5)
plt.tight_layout()
plt.show()


# ГРАФІК 4: Залежність R2 від кількості сусідів K

plt.figure(figsize=(8, 4.5))
plt.plot(k_range, r2_scores, color='black', linewidth=1.5)
plt.scatter([best_k], [best_r2], color='red', s=50, alpha=0.8, zorder=5)
plt.title('Залежність R2 від кількості сусідів K', fontsize=12)
plt.xlabel('значення k', fontsize=10)
plt.ylabel('значення R2', fontsize=10)
plt.grid(True, linestyle='--', alpha=0.5)
plt.tight_layout()
plt.show()


# ГРАФІК 5: Деталізований графік області максимуму R2
zoom_k = list(range(2, 36))
zoom_r2 = [r2_scores[k_range.index(k)] for k in zoom_k]

plt.figure(figsize=(8, 4.5))
plt.plot(zoom_k, zoom_r2, color='black', linewidth=1.5)
plt.scatter([best_k], [best_r2], color='red', s=50, alpha=0.8, zorder=5)
plt.title(
    'Деталізований графік області де перебуває максимальне значення R2',
    fontsize=11,
)
plt.xlabel('значення k', fontsize=10)
plt.ylabel('значення R2', fontsize=10)
plt.grid(True, linestyle='--', alpha=0.5)

# Додаємо текстовий підпис у нижньому лівому кутку
plt.figtext(
    0.02,
    0.01,
    f'Максимальне значення R2={best_r2:.6f} при k={best_k}',
    fontsize=9,
    ha='left',
)

plt.tight_layout(rect=[0, 0.03, 1, 1])
plt.show()